// Copies the pieces of the frontend that the API must share (types, business rules, seed data)
// into src/flags/shared so both sides always enforce the same rules.
// Run: npm run sync:shared   (do it after changing frontend/src/types.ts, lib/businessLogic.ts or data/mock.ts)
import { readFileSync, writeFileSync } from 'node:fs';

const files = [
  ['frontend/src/types.ts', 'src/flags/shared/types.ts'],
  ['frontend/src/lib/businessLogic.ts', 'src/flags/shared/rules.ts'],
  ['frontend/src/data/mock.ts', 'src/flags/shared/seed.ts'],
];

for (const [from, to] of files) {
  const code = readFileSync(from, 'utf8').replace(/from "\.\.\/types"/g, 'from "./types.js"');
  writeFileSync(to, `// GENERATED by scripts/sync-shared.mjs from ${from}. Do not edit by hand.\n${code}`);
  console.log(`${from} -> ${to}`);
}
